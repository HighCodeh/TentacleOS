#include <assert.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include "mfkey.h"
static unsigned allocations, frees, fail_at, callbacks;
void *mfkey_test_malloc(size_t bytes) {
  allocations++;
  return fail_at == allocations ? NULL : malloc(bytes);
}
void mfkey_test_free(void *pointer) {
  if (pointer != NULL) frees++;
  free(pointer);
}
static bool cancel(uint32_t work, void *context) {
  unsigned limit = *(unsigned *)context;
  (void)work;
  return ++callbacks < limit;
}
typedef struct { mfkey_pair_t pair; uint64_t key; } vector_t;
/* First vector: official Flipper iOS test. Second: FlipperMfkey standard_tests.
 * Remaining vectors generated by independent CCrapto1 at pinned iOS revision
 * 2c1c8531953110631ca471251280a1602d118011 (see docs/nfc/README.md). */
static const vector_t VECTORS[] = {
  {{0x2a234f80,0x55721809,0xce9985f6,0x772f55be,0xa27173f2,0xe386b505,0x5fa65203},UINT64_C(0xa0a1a2a3a4a5)},
  {{0x2a234f80,0xbe771bb5,0x2328dd4a,0xcaefa8a9,0x2be39d62,0x27c7fe47,0x3c270451},UINT64_C(0xa0a1a2a3a4a5)},
  {{0x00000000U,0x00000000U,0x00000000U,0x00000000U,0x00000001U,0x00000001U,0x99b5873eU},UINT64_C(0x000000000000)},
  {{0x11223344U,0x12345678U,0x89abcdefU,0x6b92be2cU,0xfedcba98U,0x76543210U,0xa1519275U},UINT64_C(0xffffffffffff)},
  {{0x10203040U,0x98765432U,0x11111111U,0x1a056debU,0x98765432U,0x22222222U,0xb101549eU},UINT64_C(0x123456abcdef)},
  {{0xffffffffU,0xffffffffU,0xffffffffU,0x5f469e6bU,0x00000000U,0xdeadbeefU,0xba7cdbddU},UINT64_C(0x010203040506)}
};
int main(void) {
  uint64_t key = 42;
  for (size_t i=0;i<sizeof(VECTORS)/sizeof(VECTORS[0]);i++) {
    allocations=frees=fail_at=0;
    assert(mfkey_recover(&VECTORS[i].pair,&key,NULL,NULL)==MFKEY_RESULT_FOUND);
    assert(key==VECTORS[i].key && allocations==frees);
  }
  mfkey_pair_t invalid=VECTORS[0].pair;
  invalid.ar1^=1;
  assert(mfkey_recover(&invalid,&key,NULL,NULL)==MFKEY_RESULT_NOT_FOUND && key==0);
  invalid=VECTORS[0].pair; invalid.nt1=invalid.nt0; invalid.nr1=invalid.nr0;
  assert(mfkey_recover(&invalid,&key,NULL,NULL)==MFKEY_RESULT_INVALID && key==0);
  assert(mfkey_recover(NULL,&key,NULL,NULL)==MFKEY_RESULT_INVALID && key==0);
  assert(mfkey_recover(&invalid,NULL,NULL,NULL)==MFKEY_RESULT_INVALID);
  for(unsigned failure=1;failure<=2;failure++) {
    allocations=frees=0;fail_at=failure;
    assert(mfkey_recover(&VECTORS[0].pair,&key,NULL,NULL)==MFKEY_RESULT_NO_MEMORY);
    assert(key==0 && frees==1 && allocations==2);
  }
  fail_at=0;
  const unsigned limits[]={1,2,300};
  for(unsigned i=0;i<3;i++) {
    unsigned limit=limits[i]; callbacks=allocations=frees=0;
    assert(mfkey_recover(&VECTORS[0].pair,&key,cancel,&limit)==MFKEY_RESULT_CANCELLED);
    assert(key==0 && callbacks==limit && allocations==frees);
  }
  puts("PASS: six independent MFKey vectors, zero key, same nonce, corruption, invalid input, allocation failure and cancellation");
}
