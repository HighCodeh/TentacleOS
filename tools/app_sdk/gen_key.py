# Generate a dev Ed25519 keypair. Writes the 32-byte private seed and emits the
# firmware trust-store header with the public key. DEV KEY: production uses a
# separately-managed key; the private key never ships in firmware.
import os

here = os.path.dirname(os.path.abspath(__file__))
fw = os.path.join(here, "..", "..", "firmware_p4", "components", "Service", "app_runtime", "include")
priv_path = os.path.join(here, "keys", "dev_ed25519.key")
hdr_path = os.path.join(fw, "tos_trust_keys.h")

def carr(b):
    return ", ".join(f"0x{x:02x}" for x in b)


def render_trust_header(public_key):
    license_notice = '''// SPDX-License-Identifier: GPL-3.0-or-later
//
// TentacleOS is free software: you can redistribute it and/or modify
// it under the terms of the GNU General Public License as published by
// the Free Software Foundation, either version 3 of the License, or
// (at your option) any later version.
//
// TentacleOS is distributed in the hope that it will be useful,
// but WITHOUT ANY WARRANTY; without even the implied warranty of
// MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE. See the
// GNU General Public License for more details.
//
// You should have received a copy of the GNU General Public License
// along with TentacleOS. If not, see <https://www.gnu.org/licenses/>.

'''
    return (license_notice +
            "// Generated by tools/app_sdk/gen_key.py. Trusted app-signing public keys.\n"
            "#ifndef TOS_TRUST_KEYS_H\n#define TOS_TRUST_KEYS_H\n#include <stdint.h>\n\n"
            "#define TOS_TRUST_KEY_COUNT 1\n"
            "static const uint8_t TOS_TRUST_KEYS[TOS_TRUST_KEY_COUNT][32] = {\n"
            "    {" + carr(public_key) + "},\n"
            "};\n#endif // TOS_TRUST_KEYS_H\n")


def main():
    import nacl.signing

    sk = nacl.signing.SigningKey.generate()
    with open(priv_path, "wb") as output:
        output.write(bytes(sk))
    with open(hdr_path, "w") as output:
        output.write(render_trust_header(bytes(sk.verify_key)))
    print(f"wrote {priv_path} (private seed) and {hdr_path} (public key)")


if __name__ == '__main__':
    main()
